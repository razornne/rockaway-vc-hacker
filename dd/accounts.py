"""Filed annual accounts (účetní závěrka) from the Czech Collection of Deeds, read by code.

The filings are PDFs; most are generated by accounting software and carry a text layer laid out in the standard
forms of Decree 500/2002 (balance sheet, income statement). Rows are found by their standard Czech labels (row
numbers differ between the full, shortened and simplified forms), and the current/prior-year columns by where the
numbers sit on the line. Nothing is guessed:

- amounts are in the unit the form states ("v celých tisících Kč" = CZK thousands) and stored in CZK;
- the balance sheet is accepted only if total assets equal total liabilities and equity, for both years;
- a company that files only a balance sheet (micro and small entities without an audit may omit the income
  statement) gets `pnl_published: False` — revenue is then "not published", never zero;
- a scanned PDF without a text layer is reported as unreadable (no OCR here).
"""
from __future__ import annotations

import io
import re
from typing import Any

BALANCE = (  # key, label pattern (case-sensitive: a label starts with a capital, a sub-item does not)
    ("total_assets", r"AKTIVA CELKEM"),
    ("fixed_assets", r"Stálá aktiva"),
    ("current_assets", r"Oběžná aktiva"),
    ("inventory", r"Zásoby\b"),
    ("receivables", r"(?<![a-zé] )Pohledávky\b(?!\s+za)"),
    ("cash", r"Peněžní prostředky"),
    ("total_equity_liabilities", r"PASIVA CELKEM"),
    ("equity", r"Vlastní kapitál"),
    ("share_capital", r"Základní kapitál"),
    ("retained_earnings", r"Výsledek hospodaření (?:z )?minulých let"),
    ("net_result", r"Výsledek hospodaření běžného účetního období"),
    ("liabilities", r"Cizí zdroje|CIZÍ ZDROJE"),
    ("long_term_liabilities", r"Dlouhodobé závazky"),
    ("short_term_liabilities", r"Krátkodobé závazky"),
)
ASSET_KEYS = {"total_assets", "fixed_assets", "current_assets", "inventory", "receivables", "cash"}
PNL = (
    ("revenue_products_services", r"Tržby z prodeje výrobků a služeb"),
    ("revenue_goods", r"Tržby za prodej zboží"),
    ("materials_services", r"Výkonová spotřeba"),
    ("personnel_costs", r"Osobní náklady"),
    ("other_operating_income", r"Ostatní provozní výnosy"),
    ("operating_result", r"Provozní výsledek hospodaření"),
    ("financial_result", r"Finanční výsledek hospodaření"),
    ("pre_tax_result", r"Výsledek hospodaření před zdaněním"),
    ("income_tax", r"Daň z příjmů(?!\s+(?:splatná|odložená))"),
    ("after_tax_result", r"Výsledek hospodaření po zdanění"),
    ("net_turnover", r"Čistý obrat za účetní období"),
)
NUM = re.compile(r"(?<![\d,.])-?(?:\d{1,3}(?: \d{3})+|\d+)(?![\d,.])")  # "85 291" or "106223"; no-break spaces normalised
# forms with a row-number column put row 1 ("001") right after AKTIVA CELKEM; others go straight to the amounts
HAS_ROWNUM = re.compile(r"AKTIVA CELKEM\s+0*1(?=\s{2,})")
ROWNUM = re.compile(r"(?<=[\s.])(\d{1,3})(?=\s{2,}|\s*$)")  # "... - F.30   18 605": a row number after a formula


def pdf_text(data: bytes) -> list[str]:
    """Text of each page, laid out as on paper; [] for a file that is not a PDF."""
    if not data.startswith(b"%PDF"):
        return []
    from pypdf import PdfReader
    try:
        reader = PdfReader(io.BytesIO(data))
        # no-break spaces (between words and inside numbers) become spaces; same length, so columns stay put
        return [re.sub("[   ]", " ", p.extract_text(extraction_mode="layout") or "") for p in reader.pages]
    except Exception:
        return []


def _num(s: str) -> int:
    return int(s.replace(" ", ""))


def _unit(text: str) -> int | None:
    if re.search(r"v\s+(?:celých\s+)?(?:tisících|tis\.)\s*(?:Kč|CZK)", text, re.I):
        return 1000
    if re.search(r"\(v\s+(?:celých\s+)?(?:Kč|CZK)\)", text, re.I):
        return 1
    return None


def _rows(lines: list[str], table, rownum: bool = True) -> dict[str, list[tuple[int, int]]]:
    """For each wanted label: the numbers after its row number (or right after the label in forms without one),
    as (value, right-edge column)."""
    found: dict[str, list[tuple[int, int]]] = {}
    for line in lines:
        for key, pat in table:
            if key in found:
                continue
            m = re.search(pat, line)
            if not m:
                continue
            start = m.end()
            if rownum:
                rn = ROWNUM.search(line, start)
                if not rn:
                    continue
                start = rn.end()
            nums = [(_num(x.group(0)), x.end()) for x in NUM.finditer(line, start)]
            found[key] = nums
            break
    return found


def _columns(rows: dict[str, list[tuple[int, int]]]) -> list[float]:
    """Column positions: clusters of the right edges of the numbers (figures are right-aligned)."""
    edges = sorted(e for nums in rows.values() for _, e in nums)
    groups: list[list[int]] = []
    for e in edges:
        if groups and e - groups[-1][-1] <= 4:
            groups[-1].append(e)
        else:
            groups.append([e])
    return [sum(g) / len(g) for g in groups if len(g) >= 2] or [sum(g) / len(g) for g in groups]


def _two_years(rows: dict[str, list[tuple[int, int]]]) -> dict[str, dict[str, int | None]]:
    """The last two columns are this year (net) and the prior year (net), in every form."""
    cols = _columns(rows)
    out = {}
    for key, nums in rows.items():
        cur = prev = None
        for value, edge in nums:
            idx = min(range(len(cols)), key=lambda i: abs(cols[i] - edge)) if cols else 0
            if idx == len(cols) - 1:
                prev = value
            elif idx == len(cols) - 2:
                cur = value
        out[key] = {"current": cur, "prior": prev}
    return out


def parse_accounts(pages: list[str]) -> dict[str, Any]:
    """Balance sheet and (if filed) income statement from the text of one or more filed PDFs."""
    text = "\n".join(pages)
    if not text.strip():
        return {"readable": False, "reason": "no text layer (scanned document); OCR is not implemented"}
    unit = _unit(text)
    period = re.search(r"ke\s+dni\s+(\d{1,2})\.\s?(\d{1,2})\.\s?(\d{4})", text)
    balance: dict[str, dict] = {}
    pnl: dict[str, dict] = {}
    rownum = bool(HAS_ROWNUM.search(text)) or not re.search(r"AKTIVA CELKEM", text)
    for page in pages:  # columns are measured per page and per statement
        lines = page.splitlines()
        if re.search(r"ROZVAHA|AKTIVA CELKEM|PASIVA CELKEM|Peněžní prostředky|Vlastní kapitál|Cizí zdroje", page):  # and continuation pages
            assets = _rows(lines, [b for b in BALANCE if b[0] in ASSET_KEYS], rownum)
            liab = _rows(lines, [b for b in BALANCE if b[0] not in ASSET_KEYS], rownum)
            for part in (assets, liab):
                if part:
                    for k, v in _two_years(part).items():
                        balance.setdefault(k, v)
        if re.search(r"VÝKAZ ZISKU A ZTRÁTY|Tržby z prodeje|Provozní výsledek hospodaření|Výsledek hospodaření před", page):
            part = _rows(lines, PNL, rownum)
            if part:
                for k, v in _two_years(part).items():
                    pnl.setdefault(k, v)
    if not balance:
        return {"readable": False, "reason": "no balance sheet found in the filed text"}
    if unit is None:
        return {"readable": False, "reason": "the unit of the amounts is not stated"}
    scale = lambda d: {k: {y: (None if v is None else v * unit) for y, v in d[k].items()} for k in d}  # noqa: E731
    balance, pnl = scale(balance), scale(pnl)
    ta, te = balance.get("total_assets", {}), balance.get("total_equity_liabilities", {})
    checks = {"assets_equal_equity_and_liabilities":
              bool(ta.get("current") is not None and ta.get("current") == te.get("current")
                   and (ta.get("prior") is None or ta.get("prior") == te.get("prior")))}
    if pnl.get("after_tax_result", {}).get("current") is not None and balance.get("net_result", {}).get("current") is not None:
        checks["net_result_matches_balance_sheet"] = pnl["after_tax_result"]["current"] == balance["net_result"]["current"]
    if not checks["assets_equal_equity_and_liabilities"]:
        return {"readable": False, "reason": "total assets do not equal total equity and liabilities as read; not used",
                "balance_as_read": balance}
    if checks.get("net_result_matches_balance_sheet") is False:  # a misread column or row: use nothing from it
        return {"readable": False, "reason": "the net result in the income statement differs from the balance sheet "
                "as read; not used", "balance_as_read": balance}
    revenue = None
    if pnl:
        parts = [pnl.get(k, {}).get("current") for k in ("revenue_products_services", "revenue_goods")]
        if any(p is not None for p in parts):
            revenue = sum(p or 0 for p in parts)
    return {"readable": True, "period_end": f"{period.group(3)}-{int(period.group(2)):02d}-{int(period.group(1)):02d}"
            if period else None, "unit_in_filing": "CZK thousands" if unit == 1000 else "CZK",
            "balance": balance, "pnl": pnl or None, "pnl_published": bool(pnl),
            "revenue": revenue, "checks": checks}
